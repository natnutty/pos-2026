export const getLocalizedCategory = (category: string, lang: Language): string => {
  const t = translations[lang];
  switch (category) {
    case 'nasi':
      return t.catNasi;
    case 'sate':
      return t.catSate;
    case 'gorengan':
      return t.catGorengan;
    case 'minuman':
      return t.catMinuman;
    case 'camilan':
      return t.catCamilan;
    default:
      return t.catLainnya;
  }
};

export const getLocalizedUnit = (unit: string, lang: Language): string => {
  const t = translations[lang];
  if (lang === 'id') return unit;

  switch (unit.toLowerCase()) {
    case 'bungkus':
      return t.unitPack;
    case 'tusuk':
      return t.unitSkewer;
    case 'pcs':
      return t.unitPcs;
    case 'gelas':
      return t.unitGlass;
    case 'porsi':
      return t.unitPortion;
    default:
      return unit;
  }
};

export const getLocalizedReason = (reason: string, lang: Language): string => {
  const t = translations[lang];
  switch (reason) {
    case 'sale':
      return t.reasonSale;
    case 'restock':
      return t.reasonRestock;
    case 'adjustment':
      return t.reasonAdjustment;
    case 'spoilage':
      return t.reasonSpoilage;
    case 'cancel_restore':
      return t.reasonCancelRestore;
    default:
      return reason;
  }
};

